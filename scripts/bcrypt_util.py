# ----------------------------------------------------------------------
# Bcrypt Base64 Encoding
# Bcrypt uses a custom base64 alphabet:
# ./ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789
# ----------------------------------------------------------------------

_BCRYPT_CHARS = "./ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
_BCRYPT_INDEX = {c: i for i, c in enumerate(_BCRYPT_CHARS)}


def _encode_base64(data: bytes, count: int) -> str:
    out = []
    idx = 0
    while count > 0:
        c1 = data[idx]
        idx += 1
        out.append(_BCRYPT_CHARS[c1 >> 2])
        c1 = (c1 & 0x03) << 4
        count -= 1
        if count == 0:
            out.append(_BCRYPT_CHARS[c1])
            break

        c2 = data[idx]
        idx += 1
        c1 |= c2 >> 4
        out.append(_BCRYPT_CHARS[c1])
        c1 = (c2 & 0x0F) << 2
        count -= 1
        if count == 0:
            out.append(_BCRYPT_CHARS[c1])
            break

        c3 = data[idx]
        idx += 1
        c1 |= c3 >> 6
        out.append(_BCRYPT_CHARS[c1])
        out.append(_BCRYPT_CHARS[c3 & 0x3F])
        count -= 1

    return "".join(out)


def _decode_base64(s: str, count: int) -> bytes:
    out = bytearray()
    s_idx = 0
    while count > 0:
        c1 = _BCRYPT_INDEX[s[s_idx]]
        s_idx += 1
        c2 = _BCRYPT_INDEX[s[s_idx]]
        s_idx += 1
        b0 = ((c1 << 2) | (c2 >> 4)) & 0xFF
        out.append(b0)
        count -= 1
        if count == 0:
            break
        c3 = _BCRYPT_INDEX[s[s_idx]]
        s_idx += 1
        b1 = ((c2 << 4) | (c3 >> 2)) & 0xFF
        out.append(b1)
        count -= 1
        if count == 0:
            break
        c4 = _BCRYPT_INDEX[s[s_idx]]
        s_idx += 1
        b2 = ((c3 << 6) | c4) & 0xFF
        out.append(b2)
        count -= 1
    return bytes(out)


