def _bytes_to_words(data: bytes) -> list[int]:
    words = []
    for i in range(0, len(data), 4):
        chunk = data[i : i + 4]
        if len(chunk) < 4:
            chunk = chunk + b"\x00" * (4 - len(chunk))
        words.append(struct.unpack(">I", chunk)[0])
    return words or [0]


def hash_bcrypt(password: str | bytes, cost: int | None = None, salt: bytes | None = None) -> str:
    """Generate OpenBSD bcrypt $2a$ hash for password."""
    if cost is None:
        cost = int(os.environ.get("ATLASOPS_BCRYPT_COST", "10"))
    if cost < 4 or cost > 31:
        raise ValueError(f"Bcrypt cost must be between 4 and 31 (got {cost})")

    # Fast path: check for external htpasswd / bcrypt CLI if available
    htpasswd_path = shutil.which("htpasswd")
    if htpasswd_path and salt is None:
        try:
            pwd_str = password if isinstance(password, str) else password.decode("utf-8")
            res = subprocess.run(
                [htpasswd_path, "-nbBC", str(cost), "", pwd_str],
                capture_output=True,
                text=True,
                check=True
            )
            line = res.stdout.strip()
            if ":" in line:
                hash_part = line.split(":", 1)[1].strip()
                if hash_part.startswith("$2y$") or hash_part.startswith("$2b$"):
                    hash_part = "$2a$" + hash_part[4:]
                return hash_part
        except Exception:
            pass

    # Pure Python implementation
    if isinstance(password, str):
        pwd_bytes = password.encode("utf-8")
    else:
        pwd_bytes = password
    # Bcrypt null-terminates the password up to 72 bytes
    pwd_bytes = pwd_bytes[:71] + b"\x00"

    if salt is None:
        salt = secrets.token_bytes(16)
    elif len(salt) != 16:
        raise ValueError("Salt must be exactly 16 bytes")

    key_words = _bytes_to_words(pwd_bytes)
    salt_words = _bytes_to_words(salt)

    bf = Blowfish()
    bf.eks_expand_state(salt_words, key_words)

    rounds = 1 << cost
    for _ in range(rounds):
        bf.expand_state(key_words)
        bf.expand_state(salt_words)

    # "OrpheanBeholderScryDoubt" in 32-bit big-endian words (6 words, 24 bytes)
    c_words = [
        0x4F727068, 0x65616E42,  # Orph eanB
        0x65686F6C, 0x64657253,  # ehol derS
        0x63727944, 0x6F756274,  # cryD oubt
    ]

    for _ in range(64):
        for i in range(0, 6, 2):
            c_words[i], c_words[i + 1] = bf.encipher(c_words[i], c_words[i + 1])

    ciphertext = struct.pack(">6I", *c_words)[:23]

    salt_str = _encode_base64(salt, 16)
    cipher_str = _encode_base64(ciphertext, 23)

    return f"$2a${cost:02d}${salt_str}{cipher_str}"


def verify_bcrypt(password: str | bytes, bcrypt_hash: str) -> bool:
    """Verify password against an OpenBSD bcrypt $2a$, $2y$, or $2b$ hash."""
    if not (bcrypt_hash.startswith("$2a$") or bcrypt_hash.startswith("$2y$") or bcrypt_hash.startswith("$2b$")):
        return False
    parts = bcrypt_hash.split("$")
    if len(parts) != 4:
        return False
    cost = int(parts[2])
    salt_and_cipher = parts[3]
    if len(salt_and_cipher) != 53:
        return False
    salt_str = salt_and_cipher[:22]
    salt_bytes = _decode_base64(salt_str, 16)
    expected_hash = hash_bcrypt(password, cost=cost, salt=salt_bytes)
    normalized_input = "$2a$" + bcrypt_hash[4:]
    return secrets.compare_digest(expected_hash, normalized_input)


def format_iso_timestamp(dt: datetime | None = None) -> str:
    """Format UTC ISO timestamp for passwordMtime."""
    if dt is None:
        dt = datetime.now(timezone.utc)
    return dt.strftime("%Y-%m-%dT%H:%M:%SZ")
